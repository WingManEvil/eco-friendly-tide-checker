"""
Parse the KMFRI 2026 official tide predictions (Mombasa) into machine-readable data.

Source: Kenya Marine & Fisheries Research Institute (KMFRI)
        "2026 HIGH-LOW AND HOURLY TIDE PREDICTIONS FOR MOMBASA AND LAMU"
        Generated with T_TIDE from real Mombasa gauge observations.
        Heights are metres above lowest astronomical tide, local time GMT+3.

Two tables are extracted:
  1. high/low events, four per day      -> TIDES    (drives the list + the peaks on the graph)
  2. hourly sea level, 24 per day       -> HOURLY   (drives the smooth curve)

Run:  pdftotext -layout kmfri-2026.pdf kmfri.txt && python parse_tides.py
Then open index.html. Both blocks are baked into it; there is no external .js file,
because on Windows a double-clicked .js runs Windows Script Host and errors out.
"""

import json
import re

MONTHS = ["JANUARY", "FEBRUARY", "MARCH", "APRIL", "MAY", "JUNE",
          "JULY", "AUGUST", "SEPTEMBER", "OCTOBER", "NOVEMBER", "DECEMBER"]
DAYS_IN = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]

DAY_ROW = re.compile(r"^(MON|TUE|WED|THU|FRI|SAT|SUN)\s+(\d{1,2})\s+(.*)$")
MONTH_HDR = re.compile(r"^\s*(" + "|".join(MONTHS) + r")\s+2026\s*$")
EVENT = re.compile(r"(\d{1,2}:\d{2}|--:--)\s+(\d+\.\d{2}|----)")

HOUR_ROW = re.compile(r"^\s*(\d{1,2})\s+((?:[\d.]+\s+){23}[\d.]+)\s*$")


def read_lines(path="kmfri.txt"):
    return open(path, encoding="utf-8", errors="replace").read().splitlines()


def parse_highlow(lines):
    start = next(i for i, l in enumerate(lines)
                 if "High-Low Tide Predictions for Mombasa" in l)
    end = next(i for i, l in enumerate(lines)
               if "High-Low Tide Predictions for Lamu" in l)

    out, month, skipped = {}, None, []
    for line in lines[start:end]:
        m = MONTH_HDR.match(line)
        if m:
            month = MONTHS.index(m.group(1)) + 1
            continue
        if not month:
            continue
        d = DAY_ROW.match(line.strip())
        if not d:
            continue

        day = int(d.group(2))
        events = EVENT.findall(d.group(3))
        if len(events) != 4:
            skipped.append((month, day, d.group(3).strip()))
            continue

        highs = [{"t": t, "h": float(h)} for t, h in events[0:2] if t != "--:--"]
        lows = [{"t": t, "h": float(h)} for t, h in events[2:4] if t != "--:--"]
        if len(highs) + len(lows) < 2:
            skipped.append((month, day, "too few tides"))
            continue

        out["2026-%02d-%02d" % (month, day)] = {
            "high": sorted(highs, key=lambda e: e["t"]),
            "low": sorted(lows, key=lambda e: e["t"]),
        }
    return out, skipped


def parse_hourly(lines):
    # The table of contents repeats these headings, so skip it: only the real
    # section banner carries the year.
    start = next(i for i, l in enumerate(lines)
                 if "2026 HOURLY TIDE PREDICTIONS FOR MOMBASA" in l.upper())
    end = next(i for i, l in enumerate(lines)
               if "Hourly Tide Predictions for Lamu" in l and i > start)

    out, month, problems = {}, None, []
    for line in lines[start:end]:
        m = MONTH_HDR.match(line)
        if m:
            month = MONTHS.index(m.group(1)) + 1
            continue
        if not month:
            continue
        d = HOUR_ROW.match(line)
        if not d:
            continue

        day = int(d.group(1))
        if day > DAYS_IN[month - 1]:
            continue
        vals = [float(x) for x in d.group(2).split()]
        if len(vals) != 24:
            problems.append((month, day, "%d values" % len(vals)))
            continue
        out["2026-%02d-%02d" % (month, day)] = vals
    return out, problems


def inject(html, name, payload, marker):
    """Replace or insert a generated data block. Keeps index.html self-contained."""
    block = ("<script>\n/* %s-START — generated by parse_tides.py, do not edit by hand */\n"
             "const %s = %s;\n/* %s-END */\n</script>" % (marker, name, payload, marker))

    if "/* %s-START" % marker in html:
        return re.sub(r"<script>\n/\* %s-START.*?/\* %s-END \*/\n</script>" % (marker, marker),
                      lambda _: block, html, flags=re.S)

    if marker == "HOURLY" and "/* DATA-END */" in html:
        cut = html.index("/* DATA-END */")
        close = html.index("</script>", cut) + len("</script>")
        return html[:close] + "\n" + block + html[close:]

    return html.replace('<script src="tides.js"></script>', block, 1)


if __name__ == "__main__":
    lines = read_lines()

    tides, skipped = parse_highlow(lines)
    hourly, problems = parse_hourly(lines)

    print("high/low days parsed:", len(tides), "| rows skipped:", len(skipped))
    print("hourly days parsed:  ", len(hourly), "| problems:", len(problems))
    for s in skipped[:5]:
        print("   skipped", s)
    for p in problems[:5]:
        print("   problem", p)

    assert len(tides) == 365, "expected 365 days of high/low, got %d" % len(tides)
    assert len(hourly) == 365, "expected 365 days of hourly, got %d" % len(hourly)

    for k, v in tides.items():
        assert 2 <= len(v["high"]) + len(v["low"]) <= 4, k
        for e in v["high"] + v["low"]:
            assert 0.0 <= e["h"] <= 4.6, (k, e)
            hh, mm = e["t"].split(":")
            assert 0 <= int(hh) < 24 and 0 <= int(mm) < 60, (k, e)

    for k, v in hourly.items():
        assert len(v) == 24, k
        assert all(0.0 <= x <= 4.6 for x in v), k

    json.dump(tides, open("tides.json", "w"), indent=0, sort_keys=True)
    json.dump(hourly, open("tides-hourly.json", "w"), indent=0, sort_keys=True)

    html = open("index.html", encoding="utf-8").read()
    html = inject(html, "TIDES", json.dumps(tides, sort_keys=True, separators=(",", ":")), "DATA")
    html = inject(html, "HOURLY", json.dumps(hourly, sort_keys=True, separators=(",", ":")), "HOURLY")
    open("index.html", "w", encoding="utf-8").write(html)

    print("\n14 Nov (Mombasa, official):", json.dumps(tides["2026-11-14"]))
    print("14 Nov hourly 00:00-23:00:", hourly["2026-11-14"][:6], "...")
    print("\nindex.html rebuilt — self-contained, %d KB" % (len(html.encode("utf-8")) // 1024))
